import assert from 'node:assert/strict';
import { GardenProgress } from '../dist/profile.js';
import { GameSave } from '../dist/save-state.js';
import { loadPreferences, savePreferences } from '../dist/preferences.js';
import { GardenSocial } from '../dist/social.js';
const values=new Map(),storage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,String(value)),removeItem:key=>values.delete(key)};
const progress=new GardenProgress({storage});await progress.init();
const run=await progress.startRun({fresh:true,mode:'science'});
await progress.checkpointRun(9000,40);
assert.equal(progress.profile.modeBestScores.science,9000);
assert.equal(progress.profile.bestScore,0);assert.equal(progress.profile.classicMergedFruits,0);
assert.equal((await progress.unlockAchievement('firstMerge',{mode:'science',runId:run.runId})).unlocked,false);
assert(!progress.profile.unlockedAchievements.includes('firstMerge'));
await progress.finishRun(10000,80);
const reloaded=new GardenProgress({storage});await reloaded.init();
assert.equal(reloaded.pendingRun.mode,'science');assert.equal(reloaded.pendingRun.result.mode,'science');
assert.equal(reloaded.profile.modeBestScores.science,10000);assert.equal(reloaded.profile.bestScore,0);
await reloaded.startRun({fresh:true,mode:'classic'});await reloaded.checkpointRun(15,2);
assert.equal(reloaded.profile.bestScore,15);assert.equal(reloaded.profile.modeBestScores.science,10000);
savePreferences({unlockedModes:['classic','science','unknown']},storage);
assert.deepEqual(loadPreferences(storage).unlockedModes,['classic','science']);
const save=new GameSave({storage});
const board={runId:run.runId,mode:'science',world:{version:2,width:600,height:720,time:1,score:42,state:'playing',mode:'science',bodies:[]},activeLevel:0,nextLevel:1,activeSpecial:false,nextSpecial:false,aimX:300,shakes:0,shakeReadyAt:0,dropCount:0,itemCount:0,roundCleared:0,maxLevel:0,watermelonMade:false,secretDiscovered:false,seedState:42,totalShakes:0,specialShakeRewards:0,discoveredLevels:[],toolReadyAt:{eraser:0,calm:0}};
assert(save.write(board));assert.equal(save.read().mode,'science');assert.equal(save.read().world.mode,'science');
assert(!save.write({...board,mode:'unknown'}));assert.equal(save.read().mode,'science','invalid save cannot replace valid science record');
const social=new GardenSocial({document:null,location:new URL('https://garden.example/'),navigator:{}});
assert.equal(social._normalRoom({code:'ABCDEFG',seed:42,mode:'science',game:'suika',players:[]}).mode,'science');
social.dispose();
console.log('PASS science records: dedicated best scores/receipts, classic achievement isolation, preferences, save validation and room mode preservation.');
